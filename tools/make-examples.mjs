// Turn examples/*.mp3 + examples/examples.json into scripts the page can load anywhere
// (even when index.html is opened straight from disk, where fetch() is blocked):
//   node tools/make-examples.mjs
//   -> js/examples.js              (list + credits, loaded with the page)
//   -> js/examples/<id>.js         (the audio, loaded only when that example is clicked)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const list = JSON.parse(await readFile(join(root, 'examples', 'examples.json'), 'utf8'));
await mkdir(join(root, 'js', 'examples'), { recursive: true });

let total = 0;
for (const ex of list) {
  const bytes = await readFile(join(root, 'examples', ex.file));
  total += bytes.length;
  const js = `/* ${ex.title} — "${ex.credit.title}" by ${ex.credit.author}, ${ex.credit.license}, ${ex.credit.url} */\n` +
    `window.ThockExamples.loaded[${JSON.stringify(ex.id)}] = ${JSON.stringify(bytes.toString('base64'))};\n`;
  await writeFile(join(root, 'js', 'examples', `${ex.id}.js`), js);
}
const meta = list.map(({ id, label, title, about, credit }) => ({ id, label, title, about, credit }));
await writeFile(join(root, 'js', 'examples.js'),
  `/* ThockScope example recordings (generated by tools/make-examples.mjs — edit examples/examples.json instead). */\n` +
  `window.ThockExamples = { list: ${JSON.stringify(meta, null, 2)}, loaded: {} };\n`);
console.log(`${list.length} examples, ${(total / 1024).toFixed(0)} KB of audio`);
